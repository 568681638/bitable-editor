#!/usr/bin/env bash
# ============================================================
#  bitable-annotator — 一键部署脚本 (阿里云 PAI DSW 容器环境)
#
#  作用：
#   1. 安装 supervisor 程序配置到 /etc/supervisor/conf.d/
#   2. 注册启动前钩子 ~/.prestart.d/00-bitable-annotator.sh
#      —— 每次容器重启时，钩子会自动把配置重新装回易失的 rootfs
#   3. 立即启动/重启服务
#
#  用法：
#    ./deploy.sh              # 部署 + 启动
#    PORT=7000 ./deploy.sh    # 用其它端口（仅影响本次启动，持久化端口请改 supervisor.conf）
#
#  可安全重复执行 (idempotent)。
# ============================================================
set -euo pipefail

# ─── 参数 ─────────────────────────────────────────────────────
NAME="bitable-annotator"
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TEMPLATE="${PROJECT_DIR}/supervisor.conf"
ENTRY="${PROJECT_DIR}/server.mjs"

NODE_BIN="${NODE_BIN:-$(command -v node || true)}"
[ -z "${NODE_BIN}" ] && NODE_BIN=/etc/dsw/node/bin/node

PORT="${PORT:-6868}"

PRESTART_DIR="${HOME}/.prestart.d"
PRESTART_HOOK="${PRESTART_DIR}/00-${NAME}.sh"

SUPERVISOR_CONF_DIR="/etc/supervisor/conf.d"
SUPERVISOR_CONF="${SUPERVISOR_CONF_DIR}/${NAME}.conf"

LOG_DIR="/etc/dsw-logs"
LOG_FILE="${LOG_DIR}/${NAME}.log"

# ─── 打印计划 ────────────────────────────────────────────────
cat <<INFO
==> 项目目录     : ${PROJECT_DIR}
==> Node 可执行  : ${NODE_BIN}
==> 启动前钩子   : ${PRESTART_HOOK}
==> supervisor 配置 : ${SUPERVISOR_CONF}
==> 运行日志     : ${LOG_FILE}
==> 端口 (本次)  : ${PORT}
INFO
echo

# ─── 前置检查 ────────────────────────────────────────────────
[ -f "${ENTRY}" ]      || { echo "ERROR: 找不到入口 ${ENTRY}"; exit 1; }
[ -f "${TEMPLATE}" ]   || { echo "ERROR: 找不到 supervisor.conf 模板 ${TEMPLATE}"; exit 1; }
[ -x "${NODE_BIN}" ]   || { echo "ERROR: node 不可执行: ${NODE_BIN} (可用 NODE_BIN=/path/to/node 覆盖)"; exit 1; }

# ─── 渲染模板 (支持 {{PROJECT_DIR}} / {{NODE}}) ──────────────
render() {
    sed -e "s|{{PROJECT_DIR}}|${PROJECT_DIR}|g" \
        -e "s|{{NODE}}|${NODE_BIN}|g" \
        "${TEMPLATE}" > "$1"
}

# ─── 1. 立即安装 supervisor 配置 ──────────────────────────────
mkdir -p "${SUPERVISOR_CONF_DIR}" "${LOG_DIR}"
render "${SUPERVISOR_CONF}"
echo "✓ supervisor 配置已安装 → ${SUPERVISOR_CONF}"

# ─── 2. 写启动前钩子 (每次容器启动前重建 /etc/supervisor/conf.d/) ─
mkdir -p "${PRESTART_DIR}"
cat > "${PRESTART_HOOK}" <<HOOK
#!/usr/bin/env bash
# Auto-generated by ${PROJECT_DIR}/deploy.sh
# DSW 入口 (/etc/dsw/bin/entrypoint) 会在启动 supervisord 之前
# 执行 \`. \$HOME/.prestart.d/*\`，本脚本利用这个钩子把 supervisor 配置
# 重新装回易失的 rootfs (/etc/supervisor/conf.d 在每次容器重启后消失)。
set -u
TEMPLATE=${TEMPLATE}
DEST=${SUPERVISOR_CONF}
[ -f "\${TEMPLATE}" ] || exit 0
mkdir -p ${SUPERVISOR_CONF_DIR}
sed -e "s|{{PROJECT_DIR}}|${PROJECT_DIR}|g" \\
    -e "s|{{NODE}}|${NODE_BIN}|g" \\
    "\${TEMPLATE}" > "\${DEST}"
HOOK
chmod +x "${PRESTART_HOOK}"
echo "✓ 启动钩子已安装 → ${PRESTART_HOOK}"

# ─── 3. 立即 (重新) 启动 ─────────────────────────────────────
PATTERN="node .*${PROJECT_DIR}/server\\.mjs"
if pgrep -f "${PATTERN}" >/dev/null; then
    echo "→ 检测到旧进程，正在停止..."
    pkill -f "${PATTERN}" || true
    for _ in 1 2 3 4 5; do
        pgrep -f "${PATTERN}" >/dev/null || break
        sleep 1
    done
    pgrep -f "${PATTERN}" >/dev/null && pkill -9 -f "${PATTERN}" || true
fi

nohup env PORT="${PORT}" NODE_ENV=production \
    "${NODE_BIN}" "${ENTRY}" \
    >> "${LOG_FILE}" 2>&1 &
disown "$!" 2>/dev/null || true

# 等待端口就绪 (最多 ~5s)
for _ in 1 2 3 4 5; do
    sleep 1
    pgrep -f "${PATTERN}" >/dev/null && break
done

if pgrep -f "${PATTERN}" >/dev/null; then
    PID=$(pgrep -f "${PATTERN}" | head -1)
    echo "✓ 服务已启动 (pid=${PID}, log=${LOG_FILE})"
    echo
    echo "验证：curl -I http://127.0.0.1:${PORT}/"
    echo "日志：tail -f ${LOG_FILE}"
else
    echo "✗ 服务未能启动，最新日志："
    tail -30 "${LOG_FILE}" 2>/dev/null || true
    exit 1
fi
