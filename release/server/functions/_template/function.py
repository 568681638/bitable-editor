# Python 批处理函数模板：复制整个 _template 文件夹，改成函数名（不要以下划线开头），入口文件保持叫 function.py，改内容，保存即生效，不用重启服务。
# 一个函数 = 一个文件夹：入口文件 function.py + 它依赖的其他文件（模块、数据、配置）都放在这个文件夹里；函数里 `import 同文件夹的模块`、
# 按相对路径读同文件夹的数据文件都行（服务把函数文件夹设为工作目录并加入 sys.path）。根目录下以 _ 开头的公共模块（_config、_asset_id）也能 import。
# 文件夹可以放在 functions/ 的任意分类目录下（不含入口文件的文件夹就是分类目录，可多层），面板里选函数时的层级和目录结构一致。以下划线或点开头的文件 / 目录会被忽略。
# 入口需要提供 META 和 run 两样东西。
#
#   META       id（全局唯一）、name（面板里显示）、inputs / outputs（参数列表）
#              inputs  : [{"name": 参数名, "label": 显示名}]，面板里每个函数卡片各自把入参映射到字段（新加函数时会沿用别处配好的同名参数的字段）
#              outputs : [{"name": 参数名, "label": 显示名, "requires": [入参名...]}]，requires 可省略（默认本函数全部入参）
#              outputs 可以不写 / 写 []：只调用、不往表格写值的函数（发通知、触发任务等），面板里直接选这个函数即可，不用选输出字段
#              batchSize（可选）：run 每次最多拿到多少行（最后一批可能不足），默认 100，范围 1 ~ 5000。面板读取 / 写回表格固定每 100 条一批，
#              调用函数时由面板按这个数攒批或拆分（比如 500 = 攒 5 个 100 一次调用）。
#              下游一次能处理很多（本地查表、纯计算）可以调大；下游慢、限流、单次耗时长（调模型）就调小
#   run(rows)  批量计算：rows 是 [{入参名: 值}, ...]（值已被面板转成文本，没映射到字段的入参不会出现），
#              必须返回与 rows 等长、顺序一致的列表，每项是 {出参名: 值}。
#              某一行算不出来：这一项返回一个异常对象（如 ValueError("原因")），只让这一行失败；
#              某个出参这一行没有值、不想写入该字段：这一项里把它设为 None，字段会保留原值（全部出参都是 None 则跳过这一行）。
#              run 里直接抛异常则整批失败，运行会中断。没有输出的函数，每项返回 {} 即可。
#              返回值要直接是目标字段类型的原生形态（数字给数字、单选给选项名、日期给毫秒时间戳、复选框给 True/False 等，不做宽松转换），详见 release/README.md。
#              一次拿到多行，可以把查询、模型推理等合并成一次请求。
#
# 数据经临时文件传递（JSON），没有大小限制。用系统的 python3 运行（可用环境变量 PYTHON_BIN 指定其他解释器），print 的内容会进服务日志。
META = {
    "id": "py_example",
    "name": "Python 示例",
    "inputs": [{"name": "text", "label": "文本"}],
    "outputs": [{"name": "upper", "label": "大写"}],
    # "batchSize": 100,  # 可选：每次调用传多少行，默认 100
}


def run(rows):
    return [{"upper": str(row["text"]).upper()} for row in rows]
